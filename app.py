"""ForgeGraph Flask app. Demo mode works locally; AlloyDB mode uses codelab model registration."""
from __future__ import annotations

import itertools
import os
import random
from typing import Any

from dotenv import load_dotenv
from flask import Flask, jsonify, render_template, request

load_dotenv()

from forgegraph.core import (
    build_diagnostic_prompt, build_retrieval_query, classify_sensor,
    demo_diagnosis, finite_number,
)
from forgegraph.services import (
    ask_gemma, db_health, evidence_for_query, graph_context, ingest_document, mode, save_telemetry,
)

app = Flask(__name__)
app.config["MAX_CONTENT_LENGTH"] = 96 * 1024
_cycle_ids = itertools.count(1)


@app.get("/")
def index():
    return render_template("index.html", mode=mode())


@app.get("/api/health")
def health():
    db_ok, db_detail = db_health()
    return jsonify({
        "status": "ok" if db_ok else "degraded",
        "mode": mode(),
        "database": {"available": db_ok, "detail": db_detail},
        "gemma_configured": bool(os.getenv("GEMMA_API_URL", "").strip()),
        "demo_note": "Rule-based demo responses are not generated by Gemma." if mode() == "demo" else None,
    }), (200 if db_ok else 503)


def _read_sensor_payload(data: dict[str, Any]) -> tuple[float, float, float]:
    pressure = finite_number(data.get("pressure", 280), "pressure")
    temperature = finite_number(data.get("temperature", 44), "temperature")
    vibration = finite_number(data.get("vibration", 2), "vibration")
    if not (0 <= pressure <= 1000 and -50 <= temperature <= 250 and 0 <= vibration <= 100):
        raise ValueError("sensor values are outside accepted demo bounds")
    return pressure, temperature, vibration


@app.post("/api/analyze")
def analyze():
    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        return jsonify({"error": "Send a JSON object with pressure, temperature and vibration."}), 400
    try:
        pressure, temperature, vibration = _read_sensor_payload(data)
    except ValueError as exc:
        return jsonify({"error": str(exc)}), 400

    classification = classify_sensor(pressure, temperature, vibration)
    retrieval_query = build_retrieval_query(pressure, temperature, vibration)
    try:
        evidence = evidence_for_query(retrieval_query, limit=4)
        graph = graph_context(classification["flags"])
        save_telemetry(f"C-{next(_cycle_ids):06d}", pressure, temperature, vibration, classification["flags"])
    except Exception as exc:
        app.logger.exception("Retrieval/database error")
        if mode() == "alloydb":
            return jsonify({"error": "AlloyDB retrieval failed; check database/model registration.", "detail": str(exc)[:160]}), 503
        evidence = []
        graph = {"nodes": [], "edges": [], "facts": []}

    prompt = build_diagnostic_prompt(pressure, temperature, vibration, classification["flags"], evidence, graph.get("facts", []))
    answer, model_status = ask_gemma(prompt)
    if answer:
        answer_kind = "gemma"
    elif mode() == "demo":
        answer = demo_diagnosis(pressure, temperature, vibration, classification["flags"], evidence)
        answer_kind = "rule-based-demo"
    else:
        answer = None
        answer_kind = model_status

    return jsonify({
        "classification": classification,
        "telemetry": {"pressure": pressure, "temperature": temperature, "vibration": vibration},
        "retrieval_query": retrieval_query,
        "evidence": evidence,
        "graph_context": graph,
        "analysis": answer,
        "analysis_kind": answer_kind,
        "message": None if answer else "Gemma analysis is unavailable. Telemetry and retrieved evidence remain available; check model service health and logs.",
        "disclaimer": "Advisory only. Follow approved plant procedures and have a qualified engineer verify any diagnosis.",
    })


@app.post("/api/documents")
def add_document():
    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        return jsonify({"error": "Send JSON with title, source and text."}), 400
    title, source, text = (data.get(key) for key in ("title", "source", "text"))
    if not all(isinstance(item, str) for item in (title, source, text)):
        return jsonify({"error": "title, source and text must be strings."}), 400
    if len(title) > 180 or len(source) > 240 or len(text) > 50000:
        return jsonify({"error": "title/source/text exceeds maximum length."}), 413
    try:
        chunks = ingest_document(title, source, text)
        return jsonify({"status": "indexed", "chunks": chunks, "mode": mode()}), 201
    except ValueError as exc:
        return jsonify({"error": str(exc)}), 400
    except Exception:
        app.logger.exception("Document ingest failed")
        return jsonify({"error": "Document ingestion failed. Check database connectivity and EmbeddingGemma registration."}), 503


@app.post("/api/telemetry/sample")
def sample_telemetry():
    """Generate demo telemetry readings only; does not control real machinery."""
    preset = (request.get_json(silent=True) or {}).get("preset", "anomaly")
    if preset == "normal":
        values = {"pressure": round(random.uniform(276, 284), 2), "temperature": round(random.uniform(42, 47), 2), "vibration": round(random.uniform(1.7, 2.4), 2)}
    else:
        values = {"pressure": round(random.uniform(246, 258), 2), "temperature": round(random.uniform(53, 61), 2), "vibration": round(random.uniform(4.8, 7.2), 2)}
    return jsonify(values)


if __name__ == "__main__":
    # For local demonstration only. Put behind appropriate network controls in any shared environment.
    app.run(host=os.getenv("HOST", "127.0.0.1"), port=int(os.getenv("PORT", "5000")), debug=False)
