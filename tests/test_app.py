"""Flask route tests. Run after installing requirements.txt."""
import os
os.environ["APP_MODE"] = "demo"
os.environ.pop("GEMMA_API_URL", None)

import pytest
pytest.importorskip("flask", reason="Install requirements.txt to run Flask route tests")
from app import app


@pytest.fixture()
def client():
    app.config.update(TESTING=True)
    with app.test_client() as test_client:
        yield test_client


def test_homepage_loads(client):
    response = client.get("/")
    assert response.status_code == 200
    assert b"ForgeGraph" in response.data


def test_analyze_returns_evidence_and_rule_based_label(client):
    response = client.post("/api/analyze", json={"pressure": 250, "temperature": 56, "vibration": 5.5})
    assert response.status_code == 200
    data = response.get_json()
    assert data["classification"]["is_anomaly"] is True
    assert data["analysis_kind"] == "rule-based-demo"
    assert "not generated by Gemma" not in data["analysis"]
    assert isinstance(data["evidence"], list)


def test_analyze_rejects_non_finite_values(client):
    response = client.post("/api/analyze", json={"pressure": "NaN", "temperature": 40, "vibration": 2})
    assert response.status_code == 400


def test_document_ingest_rejects_missing_fields(client):
    response = client.post("/api/documents", json={"title": "test"})
    assert response.status_code == 400
