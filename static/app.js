const $ = (id) => document.getElementById(id);
const analyzeButton = $('analyze');
function notice(message) { $('error-banner').textContent = message || ''; $('error-banner').classList.toggle('hidden', !message); }
function escapeText(value) { return String(value ?? ''); }
function setSeverity(classification) {
  const pill = $('severity-pill');
  pill.textContent = `${classification.severity.toUpperCase()} · ${classification.flags.length} flags`;
  pill.className = `pill ${classification.severity}`;
}
function renderGraph(graph) {
  const list = $('graph-list'); const edges = graph?.edges || [];
  $('graph-count').textContent = `${edges.length} relationship${edges.length === 1 ? '' : 's'}`;
  list.replaceChildren();
  if (!edges.length) { const p=document.createElement('p'); p.className='muted'; p.textContent='No graph relationships matched the current readings.'; list.appendChild(p); return; }
  const labels = Object.fromEntries((graph.nodes || []).map(node => [node.node_key, node.label]));
  for (const edge of edges) {
    const card=document.createElement('article'); card.className='graph-edge';
    const link=document.createElement('p'); link.className='graph-link';
    link.textContent=`${labels[edge.source_key] || edge.source_key}  →  ${edge.relation}  →  ${labels[edge.target_key] || edge.target_key}`;
    const note=document.createElement('p'); note.className='graph-note';
    note.textContent=`Confidence ${Number(edge.confidence || 0).toFixed(2)} · ${edge.source_note || 'Curated relationship; verify before acting.'}`;
    card.append(link,note); list.appendChild(card);
  }
}
function renderEvidence(items) {
  const list = $('evidence-list');
  $('evidence-count').textContent = `${items.length} source${items.length === 1 ? '' : 's'}`;
  list.replaceChildren();
  if (!items.length) {
    const empty = document.createElement('p'); empty.className = 'muted';
    empty.textContent = 'No matching maintenance references were retrieved. Add documents or check embedding registration.';
    list.appendChild(empty); return;
  }
  for (const item of items) {
    const card = document.createElement('article'); card.className = 'evidence-card';
    const title = document.createElement('h4'); title.textContent = escapeText(item.title || 'Untitled document');
    const body = document.createElement('p'); body.textContent = escapeText(item.text || item.chunk_text || '');
    const source = document.createElement('span'); source.className = 'source-label';
    source.textContent = `${escapeText(item.source || 'unknown source')} · relevance ${Number(item.similarity || 0).toFixed(2)}`;
    card.append(title, body, source); list.appendChild(card);
  }
}
async function parseResponse(response) {
  const data = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(data.error || data.message || `Request failed (${response.status})`);
  return data;
}
async function runAnalysis() {
  analyzeButton.disabled = true; notice(''); $('analysis').textContent = 'Retrieving evidence and preparing assessment…';
  try {
    const payload = {
      pressure: Number($('pressure').value), temperature: Number($('temperature').value),
      vibration: Number($('vibration').value)
    };
    const response = await fetch('/api/analyze', {method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify(payload)});
    const data = await parseResponse(response);
    setSeverity(data.classification);
    $('analysis').textContent = data.analysis || data.message || 'AI analysis unavailable.';
    $('model-pill').textContent = data.analysis_kind === 'gemma' ? 'GEMMA RESPONSE' : data.analysis_kind === 'rule-based-demo' ? 'RULE-BASED DEMO' : 'AI UNAVAILABLE';
    $('disclaimer').textContent = data.disclaimer || 'Advisory only.';
    renderEvidence(data.evidence || []);
    renderGraph(data.graph_context || {nodes:[],edges:[]});
    if (!data.analysis) notice(data.message || 'AI analysis unavailable; sensor values were processed.');
    else if (data.analysis_kind !== 'gemma') notice('This response is not generated by Gemma. Configure GEMMA_API_URL to enable the model, and use APP_MODE=alloydb for vector retrieval.');
  } catch (error) {
    $('analysis').textContent = 'Could not complete analysis.';
    notice(error.message || 'Unexpected request error.');
  } finally { analyzeButton.disabled = false; }
}
async function loadSample(preset) {
  try {
    const data = await parseResponse(await fetch('/api/telemetry/sample', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({preset})}));
    $('pressure').value = data.pressure; $('temperature').value = data.temperature; $('vibration').value = data.vibration;
    await runAnalysis();
  } catch(error) { notice(error.message); }
}
$('analyze').addEventListener('click', runAnalysis);
$('normal-sample').addEventListener('click', () => loadSample('normal'));
$('anomaly-sample').addEventListener('click', () => loadSample('anomaly'));
$('ingest-form').addEventListener('submit', async (event) => {
  event.preventDefault(); $('ingest-result').textContent = 'Indexing…';
  try {
    const data = await parseResponse(await fetch('/api/documents', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({title:$('doc-title').value,source:$('doc-source').value,text:$('doc-text').value})}));
    $('ingest-result').textContent = `Indexed ${data.chunks} chunk(s).`;
    $('doc-text').value = '';
  } catch(error) { $('ingest-result').textContent = error.message; }
});
(async () => {
  try {
    const data = await parseResponse(await fetch('/api/health'));
    $('system-status').textContent = data.database.available ? (data.mode === 'alloydb' ? 'AlloyDB connected' : 'Demo mode ready') : 'Database unavailable';
    if (data.mode === 'demo') notice('DEMO MODE: local lexical retrieval and rule-based analysis are used unless GEMMA_API_URL is configured. No real machine is connected.');
  } catch(error) { $('system-status').textContent = 'Service health unavailable'; notice(error.message); }
})();
